/** Inner parts of a sentence pattern: an on-screen phrase, a short date ("Sat, 21 Nov") or a time-ago ("5 d ago"). */
const phrase = (text: string) => hiPhrases[text] ?? text;
function day(text: string) {
  const m = /^(Mon|Tue|Wed|Thu|Fri|Sat|Sun), (\d+) (\w{3})$/.exec(text);
  return m ? `${WEEKDAYS[m[1]]}, ${m[2]} ${MONTHS[m[3]] ?? m[3]}` : text;
}
function ago(text: string) {
  if (text === 'just now') return 'अभी';
  const m = /^(\d+) (min|h|d) ago$/.exec(text);
  return m ? `${m[1]} ${m[2] === 'min' ? 'मिनट' : m[2] === 'h' ? 'घंटे' : 'दिन'} पहले` : text;
}

